/**
 * API functions for the catalogs admin screen (ISSUE-031, contract C27).
 *
 * All HTTP goes through `apiClient` (never raw axios/fetch), per
 * CLAUDE.frontend.md Section 7. `apiClient`'s baseURL already includes
 * `/api/v1`; the backend mounts the catalogs router at `/catalogs`.
 *
 * AiutoX ERP Core -- Frankpach
 */

import apiClient from "~/lib/api/client";
import type {
  StandardListResponse,
  StandardResponse,
} from "~/lib/api/types/common.types";
import type {
  CatalogAdminItem,
  CatalogAdminItemsResponse,
  CatalogItemCreateBody,
  CatalogItemResetBody,
  CatalogItemUpdateBody,
  CatalogItemVersion,
  CatalogListAdmin,
  CatalogListVersion,
  CatalogOrderBody,
  CatalogOrderResponse,
  FetchCatalogAdminItemsParams,
  FetchCatalogListsParams,
  FetchCatalogVersionsParams,
} from "../types/catalogsAdmin.types";

/** TanStack Query key of the admin catalog lists (invalidate it after any list-level change). */
export const CATALOG_LISTS_QUERY_KEY = ["catalogs-admin", "lists"] as const;

/**
 * The admin screen searches and groups client-side, so it asks for the
 * largest page the backend allows (`page_size` le=100) in a single call.
 */
const ADMIN_LISTS_PAGE_SIZE = 100;

/**
 * `GET /catalogs` -- every catalog list the viewer may govern or manage,
 * each with its `viewer_capabilities` (ISSUE-016, AC-API-08/09).
 */
export async function fetchCatalogLists(
  params?: FetchCatalogListsParams
): Promise<StandardListResponse<CatalogListAdmin>> {
  const response = await apiClient.get<StandardListResponse<CatalogListAdmin>>(
    "/catalogs",
    { params: { page_size: ADMIN_LISTS_PAGE_SIZE, ...params } }
  );
  return response.data;
}

/**
 * `GET /catalogs/{list_key}/admin-items` -- every item of one catalog list
 * with its admin state (origin, hidden, modified, deprecated) plus the list
 * itself (ISSUE-016, AC-API-10, contract C13). Not paginated. Requires
 * `can_view_admin` on the list (403 otherwise; 404 `CATALOG_LIST_NOT_FOUND`
 * for an unknown key). ISSUE-034.
 *
 * `include_deprecated` is always sent; `q` only when non-empty.
 */
export async function fetchCatalogAdminItems(
  listKey: string,
  params?: FetchCatalogAdminItemsParams
): Promise<StandardResponse<CatalogAdminItemsResponse>> {
  const query: { include_deprecated: boolean; q?: string } = {
    include_deprecated: params?.includeDeprecated ?? false,
  };
  if (params?.q) {
    query.q = params.q;
  }
  const response = await apiClient.get<
    StandardResponse<CatalogAdminItemsResponse>
  >(`/catalogs/${encodeURIComponent(listKey)}/admin-items`, { params: query });
  return response.data;
}

function catalogItemPath(listKey: string, code: string): string {
  return `/catalogs/${encodeURIComponent(listKey)}/items/${encodeURIComponent(code)}`;
}

/**
 * `PATCH /catalogs/{list_key}/items/{code}` -- relabel and/or hide one item
 * for the tenant (ISSUE-017, AC-API-11/12/13, contract C14). Requires
 * `can_manage`. The backend body uses `extra="forbid"`, so only the fields
 * actually given are sent. 409 `CATALOG_LAST_VISIBLE_ITEM` when hiding the
 * last visible item. ISSUE-035.
 */
export async function updateCatalogItem(
  listKey: string,
  code: string,
  body: CatalogItemUpdateBody
): Promise<StandardResponse<CatalogAdminItem>> {
  const payload: CatalogItemUpdateBody = {};
  if (body.labels !== undefined) payload.labels = body.labels;
  if (body.is_hidden !== undefined) payload.is_hidden = body.is_hidden;
  if (body.change_reason !== undefined) {
    payload.change_reason = body.change_reason;
  }
  const response = await apiClient.patch<StandardResponse<CatalogAdminItem>>(
    catalogItemPath(listKey, code),
    payload
  );
  return response.data;
}

/**
 * `POST /catalogs/{list_key}/items` -- add a tenant item to an extensible
 * list (ISSUE-019, AC-API-15/16, contract C16). Requires `can_add_items`.
 * 201 with the created item, whose `code` is generated by the server. The
 * backend body uses `extra="forbid"`, so `change_reason` is only sent when
 * given and `code` never is. ISSUE-037.
 */
export async function addCatalogItem(
  listKey: string,
  body: CatalogItemCreateBody
): Promise<StandardResponse<CatalogAdminItem>> {
  const payload: CatalogItemCreateBody = { labels: body.labels };
  if (body.change_reason !== undefined) {
    payload.change_reason = body.change_reason;
  }
  const response = await apiClient.post<StandardResponse<CatalogAdminItem>>(
    `/catalogs/${encodeURIComponent(listKey)}/items`,
    payload
  );
  return response.data;
}

/**
 * `POST /catalogs/{list_key}/items/{code}/reset` -- delete the tenant's
 * override of a system item, restoring its default labels, order and
 * visibility (ISSUE-020, AC-API-17, contract C17). Requires `can_manage`.
 * The body is required by the endpoint but may be empty. ISSUE-035.
 */
export async function resetCatalogItem(
  listKey: string,
  code: string,
  body: CatalogItemResetBody = {}
): Promise<StandardResponse<CatalogAdminItem>> {
  const payload: CatalogItemResetBody = {};
  if (body.change_reason !== undefined) {
    payload.change_reason = body.change_reason;
  }
  const response = await apiClient.post<StandardResponse<CatalogAdminItem>>(
    `${catalogItemPath(listKey, code)}/reset`,
    payload
  );
  return response.data;
}

/**
 * `PUT /catalogs/{list_key}/order` -- set the tenant's order of a list
 * (ISSUE-018, AC-API-14, contract C15). Requires `can_manage`. `codes` must
 * be an exact permutation of every non-deprecated effective code (hidden
 * items included); otherwise 422 `CATALOG_ORDER_MISMATCH` with
 * `details.missing/unexpected/duplicated`. The backend body uses
 * `extra="forbid"`, so `change_reason` is only sent when given. ISSUE-036.
 */
export async function reorderCatalogItems(
  listKey: string,
  body: CatalogOrderBody
): Promise<StandardResponse<CatalogOrderResponse>> {
  const payload: CatalogOrderBody = { codes: body.codes };
  if (body.change_reason !== undefined) {
    payload.change_reason = body.change_reason;
  }
  const response = await apiClient.put<StandardResponse<CatalogOrderResponse>>(
    `/catalogs/${encodeURIComponent(listKey)}/order`,
    payload
  );
  return response.data;
}

/**
 * `GET /catalogs/{list_key}/versions` -- one page of a list's history,
 * newest first (ISSUE-022, AC-API-26, contract C19). Requires
 * `can_view_admin`. ISSUE-038.
 */
export async function fetchCatalogListVersions(
  listKey: string,
  params: FetchCatalogVersionsParams
): Promise<StandardListResponse<CatalogListVersion>> {
  const response = await apiClient.get<
    StandardListResponse<CatalogListVersion>
  >(`/catalogs/${encodeURIComponent(listKey)}/versions`, {
    params: { page: params.page, page_size: params.page_size },
  });
  return response.data;
}

/**
 * `GET /catalogs/{list_key}/items/{code}/versions` -- one page of an item's
 * history, newest first, including the tenant's own edits (ISSUE-022,
 * AC-API-25, contract C19). Requires `can_view_admin`. ISSUE-038.
 */
export async function fetchCatalogItemVersions(
  listKey: string,
  code: string,
  params: FetchCatalogVersionsParams
): Promise<StandardListResponse<CatalogItemVersion>> {
  const response = await apiClient.get<
    StandardListResponse<CatalogItemVersion>
  >(`${catalogItemPath(listKey, code)}/versions`, {
    params: { page: params.page, page_size: params.page_size },
  });
  return response.data;
}
